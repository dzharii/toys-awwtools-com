import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const packageRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const sourcePath = resolve(packageRoot, "src/tokens.json");
const outputDirectory = resolve(packageRoot, "dist");

const tokenPrefix = "--my-ds";

function toKebabCase(value) {
  return value
    .replace(/([a-z0-9])([A-Z])/g, "$1-$2")
    .replace(/[\s_]+/g, "-")
    .toLowerCase();
}

function getValueByPath(root, path) {
  return path.split(".").reduce((current, part) => current?.[part], root);
}

function resolveTokenValue(value, root) {
  if (typeof value !== "string") {
    return value;
  }

  return value.replace(/\{([^}]+)\}/g, (_, referencePath) => {
    const referencedValue = getValueByPath(root, referencePath);

    if (referencedValue === undefined) {
      throw new Error(`Unknown token reference: ${referencePath}`);
    }

    return resolveTokenValue(referencedValue, root);
  });
}

function flattenTokens(group, root, pathParts = []) {
  return Object.entries(group).flatMap(([key, value]) => {
    const nextPathParts = [...pathParts, toKebabCase(key)];

    if (value && typeof value === "object" && !Array.isArray(value)) {
      return flattenTokens(value, root, nextPathParts);
    }

    return [
      {
        name: `${tokenPrefix}-${nextPathParts.join("-")}`,
        path: nextPathParts.join("."),
        value: resolveTokenValue(value, root),
      },
    ];
  });
}

function createCssBlock(selector, tokens) {
  const declarations = tokens
    .map((token) => `  ${token.name}: ${token.value};`)
    .join("\n");

  return `${selector} {\n${declarations}\n}\n`;
}

function createAliasBlock(selector, tokens) {
  const declarations = tokens
    .map((token) => {
      const aliasName = token.name.replace(`${tokenPrefix}-`, "--");
      return `  ${aliasName}: var(${token.name});`;
    })
    .join("\n");

  return `${selector} {\n${declarations}\n}\n`;
}

function createThemeAliasBlock(selector, tokens) {
  const declarations = tokens
    .map((token) => {
      const [, , ...themePathParts] = token.path.split(".");
      return `  --theme-${themePathParts.join("-")}: var(${token.name});`;
    })
    .join("\n");

  return `${selector} {\n${declarations}\n}\n`;
}

async function buildTokens() {
  const source = JSON.parse(await readFile(sourcePath, "utf8"));
  await mkdir(outputDirectory, { recursive: true });

  const globalTokens = flattenTokens(source.global, source, ["global"]);
  const semanticTokens = flattenTokens(source.semantic, source, ["semantic"]);
  const tokenPayload = {
    meta: source.meta,
    global: globalTokens,
    semantic: semanticTokens,
    themes: {},
  };

  const sharedCss = [
    "/* Generated by packages/tokens/scripts/build-tokens.mjs. Do not edit by hand. */",
    createCssBlock(":root", [...globalTokens, ...semanticTokens]),
    createAliasBlock(":root", [...globalTokens, ...semanticTokens]),
  ].join("\n");

  await writeFile(resolve(outputDirectory, "tokens.css"), sharedCss);

  for (const [themeName, themeGroup] of Object.entries(source.themes)) {
    const themeTokens = flattenTokens(themeGroup, source, ["theme", themeName]);
    tokenPayload.themes[themeName] = themeTokens;
    const selectorName = toKebabCase(themeName);
    const selector =
      themeName === "default"
        ? `:root,\n[data-theme="${selectorName}"]`
        : `[data-theme="${selectorName}"]`;

    const themeCss = [
      "/* Generated by packages/tokens/scripts/build-tokens.mjs. Do not edit by hand. */",
      createCssBlock(selector, themeTokens),
      createThemeAliasBlock(selector, themeTokens),
    ].join("\n");

    await writeFile(resolve(outputDirectory, `theme-${selectorName}.css`), themeCss);
  }

  await writeFile(
    resolve(outputDirectory, "tokens.json"),
    `${JSON.stringify(tokenPayload, null, 2)}\n`,
  );

  console.log(`Built tokens into ${outputDirectory}`);
}

await buildTokens();

if (process.argv.includes("--watch")) {
  const { watch } = await import("node:fs");
  console.log("Watching token source files...");
  watch(resolve(packageRoot, "src"), { recursive: true }, async () => {
    try {
      await buildTokens();
    } catch (error) {
      console.error(error);
    }
  });
}
