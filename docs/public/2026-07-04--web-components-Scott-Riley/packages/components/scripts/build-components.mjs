import { cp, mkdir, readFile, rm, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { componentDefinitions } from "../src/component-definitions.js";

const packageRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const sourceDirectory = resolve(packageRoot, "src");
const outputDirectory = resolve(packageRoot, "dist");

function createManifest() {
  return {
    schemaVersion: "1.0.0",
    readme: "README.md",
    modules: componentDefinitions.map((componentDefinition) => ({
      kind: "javascript-module",
      path: componentDefinition.modulePath.replace("./", "dist/"),
      declarations: [
        {
          kind: "class",
          declaration: {
            name: componentDefinition.className,
            module: componentDefinition.modulePath
          },
          name: componentDefinition.className,
          tagName: componentDefinition.tagName,
          customElement: true,
          description: componentDefinition.description,
          displayName: componentDefinition.displayName,
          status: componentDefinition.status,
          members: componentDefinition.props.map((propertyDefinition) => ({
            kind: "field",
            name: propertyDefinition.name,
            type: { text: propertyDefinition.type },
            default: propertyDefinition.default,
            description: propertyDefinition.description,
            attribute: propertyDefinition.name
          }))
        }
      ]
    }))
  };
}

async function buildComponents() {
  await rm(outputDirectory, { recursive: true, force: true });
  await mkdir(outputDirectory, { recursive: true });
  await cp(sourceDirectory, outputDirectory, { recursive: true });

  const css = await readFile(resolve(sourceDirectory, "styles.css"), "utf8");
  await writeFile(
    resolve(outputDirectory, "bundle.css"),
    `/* Generated by packages/components/scripts/build-components.mjs. Do not edit by hand. */\n${css}`,
  );

  await writeFile(
    resolve(outputDirectory, "custom-elements.json"),
    `${JSON.stringify(createManifest(), null, 2)}\n`,
  );

  console.log(`Built components into ${outputDirectory}`);
}

await buildComponents();

if (process.argv.includes("--watch")) {
  const { watch } = await import("node:fs");
  console.log("Watching component source files...");
  watch(sourceDirectory, { recursive: true }, async () => {
    try {
      await buildComponents();
    } catch (error) {
      console.error(error);
    }
  });
}
