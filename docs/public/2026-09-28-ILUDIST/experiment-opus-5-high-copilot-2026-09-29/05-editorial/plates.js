/* ══════════════════════════════════════════════════════════════════
   ILUD QUARTERLY — plates
   The issue is illustrated, but nothing in it is a photograph and
   nothing in it was generated by a model. Each plate is drawn here,
   in the browser, from the entry's own identifier: a warm wash, an
   architectural silhouette, a shaft of light and a cast shadow, with
   a little printed grain over the whole. The same entry always
   produces the same plate.
   ══════════════════════════════════════════════════════════════════ */
window.PLATES = (function () {
'use strict';

/* a small deterministic generator, seeded from a string */
function seed(str) {
  var h = 2166136261;
  for (var i = 0; i < str.length; i++) { h ^= str.charCodeAt(i); h = Math.imul(h, 16777619); }
  return function () {
    h += 0x6D2B79F5; var t = h;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

/* the pigments of the issue — clay, ochre, maroon, umber, olive, rose */
var PIG = [
  { a: '#8d3a2c', b: '#3a1512', c: '#e7bb8e' },
  { a: '#a8562c', b: '#43201a', c: '#f0cf9f' },
  { a: '#6d2c26', b: '#2c110f', c: '#dda77c' },
  { a: '#95673a', b: '#3a2617', c: '#efd6ab' },
  { a: '#8a6a30', b: '#332612', c: '#e5d2a4' },
  { a: '#9e4a46', b: '#3d1a1a', c: '#eec3ae' },
  { a: '#7d4a30', b: '#31190f', c: '#e8c398' },
  { a: '#5f4a3c', b: '#241a14', c: '#dcc6ad' }
];

var uid = 0;

/* kind: 'arch' (tall, round-headed), 'square', 'band' (wide) */
function plate(id, kind, cls) {
  var r = seed(id + '|' + kind);
  var p = PIG[Math.floor(r() * PIG.length)];
  var n = 'p' + (++uid);
  var W = kind === 'square' ? 100 : kind === 'band' ? 160 : 100;
  var H = kind === 'square' ? 100 : kind === 'band' ? 90 : 165;

  /* the architecture: how many openings, how deep, where the light falls */
  var lean = (r() * 2 - 1) * 12;          /* the light's angle           */
  var open = 0.34 + r() * 0.3;            /* width of the main opening   */
  var sill = 0.52 + r() * 0.22;           /* where the floor line sits   */
  var deep = r() < 0.5;                   /* a recess, or a column       */
  var pill = r() < 0.42;                  /* a vessel on the floor       */
  var drap = r() < 0.38;                  /* a hanging fold              */

  var ax = W * (0.5 - open / 2), aw = W * open;
  var ay = H * 0.06, ah = H * sill - ay;
  var rad = aw / 2;

  var s = '';
  s += '<defs>';
  s += '<linearGradient id="' + n + 'w" x1="0" y1="0" x2="0.4" y2="1">' +
       '<stop offset="0" stop-color="' + p.a + '"/>' +
       '<stop offset="1" stop-color="' + p.b + '"/></linearGradient>';
  s += '<linearGradient id="' + n + 'f" x1="0" y1="0" x2="0.2" y2="1">' +
       '<stop offset="0" stop-color="' + p.b + '"/>' +
       '<stop offset="1" stop-color="' + p.a + '" stop-opacity=".62"/></linearGradient>';
  s += '<linearGradient id="' + n + 'l" x1="0" y1="0" x2="0.5" y2="1">' +
       '<stop offset="0" stop-color="' + p.c + '" stop-opacity=".92"/>' +
       '<stop offset="1" stop-color="' + p.c + '" stop-opacity="0"/></linearGradient>';
  s += '<radialGradient id="' + n + 'v" cx="0.5" cy="0.36" r="0.78">' +
       '<stop offset="0" stop-color="#000" stop-opacity="0"/>' +
       '<stop offset="1" stop-color="#000" stop-opacity=".46"/></radialGradient>';
  s += '<clipPath id="' + n + 'c"><rect x="0" y="0" width="' + W + '" height="' + H +
       '" rx="' + (kind === 'arch' ? rad * 0.98 : 0) + '" ry="' + (kind === 'arch' ? rad * 0.98 : 0) + '"/></clipPath>';
  s += '<filter id="' + n + 'g" x="0" y="0" width="100%" height="100%">' +
       '<feTurbulence type="fractalNoise" baseFrequency="0.86" numOctaves="3" seed="' +
       Math.floor(r() * 90) + '" result="t"/>' +
       '<feColorMatrix in="t" type="saturate" values="0"/>' +
       '<feComponentTransfer><feFuncA type="linear" slope=".26"/></feComponentTransfer></filter>';
  s += '<filter id="' + n + 'b" x="-30%" y="-30%" width="160%" height="160%">' +
       '<feGaussianBlur stdDeviation="' + (1.6 + r() * 2.2).toFixed(2) + '"/></filter>';
  s += '</defs>';

  s += '<g clip-path="url(#' + n + 'c)">';
  /* the wall */
  s += '<rect x="0" y="0" width="' + W + '" height="' + H + '" fill="url(#' + n + 'w)"/>';
  /* the floor */
  s += '<rect x="0" y="' + (H * sill).toFixed(1) + '" width="' + W + '" height="' + (H * (1 - sill)).toFixed(1) +
       '" fill="url(#' + n + 'f)"/>';

  /* the opening — a round-headed arch, recessed or columned */
  var archD = 'M' + ax.toFixed(1) + ' ' + (ay + ah).toFixed(1) +
              ' V' + (ay + rad).toFixed(1) +
              ' A' + rad.toFixed(1) + ' ' + rad.toFixed(1) + ' 0 0 1 ' + (ax + aw).toFixed(1) + ' ' + (ay + rad).toFixed(1) +
              ' V' + (ay + ah).toFixed(1) + ' Z';
  if (deep) {
    s += '<path d="' + archD + '" fill="' + p.b + '" opacity=".92"/>';
    s += '<path d="' + archD + '" fill="url(#' + n + 'l)" opacity=".2"/>';
  } else {
    s += '<path d="' + archD + '" fill="' + p.c + '" opacity=".14"/>';
    s += '<path d="' + archD + '" fill="none" stroke="' + p.c + '" stroke-opacity=".3" stroke-width=".9"/>';
  }

  /* the shaft of light, leaning */
  var lw = W * (0.24 + r() * 0.2);
  var lx = W * (0.08 + r() * 0.44);
  s += '<g opacity="' + (0.3 + r() * 0.26).toFixed(2) + '">' +
       '<path d="M' + lx.toFixed(1) + ' 0 L' + (lx + lw).toFixed(1) + ' 0 L' +
       (lx + lw + lean * 2.4).toFixed(1) + ' ' + H + ' L' + (lx + lean * 2.4).toFixed(1) + ' ' + H + ' Z" ' +
       'fill="url(#' + n + 'l)"/></g>';

  /* a vessel standing on the floor */
  if (pill) {
    var vx = W * (0.2 + r() * 0.56), vy = H * sill, vr = W * (0.07 + r() * 0.07);
    s += '<ellipse cx="' + (vx + vr * 1.5).toFixed(1) + '" cy="' + (vy + vr * 0.34).toFixed(1) +
         '" rx="' + (vr * 2.1).toFixed(1) + '" ry="' + (vr * 0.46).toFixed(1) +
         '" fill="' + p.b + '" opacity=".5" filter="url(#' + n + 'b)"/>';
    s += '<path d="M' + (vx - vr).toFixed(1) + ' ' + (vy - vr * 1.1).toFixed(1) +
         ' q' + vr.toFixed(1) + ' ' + (vr * 1.5).toFixed(1) + ' ' + (vr * 2).toFixed(1) + ' 0 Z" ' +
         'fill="' + p.c + '" opacity=".78"/>';
    s += '<rect x="' + (vx - vr * 1.12).toFixed(1) + '" y="' + (vy - vr * 1.22).toFixed(1) +
         '" width="' + (vr * 2.24).toFixed(1) + '" height="' + (vr * 0.2).toFixed(1) +
         '" rx="' + (vr * 0.1).toFixed(1) + '" fill="' + p.c + '" opacity=".6"/>';
  }

  /* a hanging fold of cloth */
  if (drap) {
    var dx = W * (r() < 0.5 ? 0.04 : 0.78), dw2 = W * 0.18;
    s += '<path d="M' + dx.toFixed(1) + ' 0 h' + dw2.toFixed(1) +
         ' q' + (-dw2 * 0.3).toFixed(1) + ' ' + (H * 0.44).toFixed(1) + ' ' + (-dw2 * 0.1).toFixed(1) + ' ' + (H * 0.78).toFixed(1) +
         ' q' + (-dw2 * 0.4).toFixed(1) + ' ' + (H * 0.1).toFixed(1) + ' ' + (-dw2 * 0.86).toFixed(1) + ' ' + (-H * 0.04).toFixed(1) +
         ' Z" fill="' + p.b + '" opacity=".55"/>';
  }

  /* the cast shadow of the opening, thrown across the floor */
  s += '<path d="M' + (ax + lean).toFixed(1) + ' ' + (H * sill).toFixed(1) +
       ' L' + (ax + aw + lean).toFixed(1) + ' ' + (H * sill).toFixed(1) +
       ' L' + (ax + aw + lean * 3.6).toFixed(1) + ' ' + H + ' L' + (ax + lean * 3.6).toFixed(1) + ' ' + H + ' Z" ' +
       'fill="' + p.c + '" opacity=".15" filter="url(#' + n + 'b)"/>';

  /* vignette, then the printed grain */
  s += '<rect x="0" y="0" width="' + W + '" height="' + H + '" fill="url(#' + n + 'v)"/>';
  s += '<rect x="0" y="0" width="' + W + '" height="' + H + '" filter="url(#' + n + 'g)" opacity=".5" style="mix-blend-mode:overlay"/>';
  s += '</g>';

  return '<svg class="plate ' + (cls || '') + '" viewBox="0 0 ' + W + ' ' + H +
    '" preserveAspectRatio="xMidYMid slice" role="img" aria-hidden="true" focusable="false">' + s + '</svg>';
}

return { plate: plate, seed: seed };
})();
