import { mkdir, readdir, readFile, writeFile, cp, rm, stat } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import type { Descriptor } from "../src/sdk/types";
import { validateDescriptor, validateAudio } from "./metadata";
import { auditFeature } from "./security";
import { validateIcon } from "./icons";
const root = fileURLToPath(new URL("../", import.meta.url));
process.chdir(root);
await mkdir("src/generated", { recursive: true });
await mkdir(".build", { recursive: true });
const entries: Descriptor[] = [];
for (const dir of (await readdir("src/effects")).sort()) {
  const data: unknown = JSON.parse(await readFile(`src/effects/${dir}/effect.json`, "utf8"));
  validateDescriptor(
    data,
    dir,
    entries.map((e) => e.id),
  );
  if (!data.enabled) continue;
  await stat(`src/effects/${dir}/index.ts`);
  await stat(`src/effects/${dir}/attribution.md`);
  await stat(`src/effects/${dir}/contract.test.ts`);
  const art = await readFile(`src/effects/${dir}/icon.svg`, "utf8");
  validateIcon(art, dir);
  data.iconSvg = art;
  const sound: unknown = JSON.parse(await readFile(`src/effects/${dir}/audio.json`, "utf8"));
  validateAudio(sound);
  if (!data.capabilities.audio) throw new Error(`Missing audio capability: ${dir}`);
  data.audioProfile = sound;
  if (process.argv.includes("--release") && data.status !== "verified")
    throw new Error(`Native review required: ${dir}`);
  entries.push(data);
}
if (!entries.length) throw new Error("Empty registry");
await writeFile(
  "src/generated/catalog.ts",
  `// Generated by tools/build.ts. Edit feature-local metadata instead.\nimport type { Descriptor } from '../sdk/types';\nexport const catalog: Descriptor[] = ${JSON.stringify(entries, null, 2)};\n`,
);
// Reject unsafe API use and cross-feature coupling before bundling.
for (const e of entries) await auditFeature(`src/effects/${e.id}`);
await rm("dist", { recursive: true, force: true });
await mkdir("dist/effects", { recursive: true });
await cp("public", "dist", { recursive: true });
const shared = await Bun.build({
  entrypoints: ["src/background.ts", "src/popup.ts", "src/runtime/content.ts"],
  outdir: "dist",
  naming: "[name].js",
  format: "iife",
  target: "browser",
  minify: true,
  loader: { ".css": "text" },
});
if (!shared.success) throw new AggregateError(shared.logs, "Core build failed");
for (const e of entries) {
  const file = `.build/${e.id}.ts`;
  await writeFile(
    file,
    `import module from '../src/effects/${e.id}/index';\nif(!globalThis.__angerReliefToyV1)throw new Error('RUNTIME_REQUIRED');\nglobalThis.__angerReliefToyV1.register('${e.id}',module);\n`,
  );
  const result = await Bun.build({
    entrypoints: [file],
    outdir: "dist/effects",
    naming: `${e.id}.js`,
    format: "iife",
    target: "browser",
    minify: true,
  });
  if (!result.success) throw new AggregateError(result.logs, `Build failed: ${e.id}`);
}
await cp("src/ui/style.css", "dist/ui.css");
const manifest = {
  manifest_version: 3,
  name: "Anger Relief Toy",
  version: "0.3.0",
  description: "Equip playful tools, use them repeatedly, and put them away to restore the page.",
  minimum_chrome_version: "120",
  permissions: ["activeTab", "scripting", "storage"],
  background: { service_worker: "background.js" },
  action: {
    default_title: "Anger Relief Toy",
    default_popup: "popup.html",
    default_icon: {
      16: "icons/16.png",
      32: "icons/32.png",
      48: "icons/48.png",
      128: "icons/128.png",
    },
  },
  icons: { 16: "icons/16.png", 48: "icons/48.png", 128: "icons/128.png" },
  commands: {
    "open-wheel": {
      suggested_key: { default: "Alt+Shift+A" },
      description: "Open rotating action dial",
    },
  },
  content_security_policy: {
    extension_pages: "script-src 'self'; object-src 'none'; base-uri 'none'",
  },
};
await writeFile("dist/manifest.json", JSON.stringify(manifest, null, 2) + "\n");
await writeFile(
  "dist/credits.json",
  JSON.stringify(
    entries.map((e) => ({ id: e.id, ...e.source })),
    null,
    2,
  ),
);
const sizes: Record<string, number> = {};
for (const name of [
  "content.js",
  "background.js",
  "popup.js",
  ...entries.map((e) => `effects/${e.id}.js`),
])
  sizes[name] = (await stat(`dist/${name}`)).size;
await mkdir("evidence", { recursive: true });
await writeFile(
  "evidence/bundle-sizes.json",
  JSON.stringify(
    {
      version: "0.3.0",
      runtimeDependencies: 0,
      sizes,
      totalJavaScriptBytes: Object.values(sizes).reduce((a, b) => a + b, 0),
    },
    null,
    2,
  ),
);
console.log(
  `Built ${entries.length} independent tools. ${Object.values(sizes).reduce((a, b) => a + b, 0)} JS bytes. No runtime dependencies.`,
);
